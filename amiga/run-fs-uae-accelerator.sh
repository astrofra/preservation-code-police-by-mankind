#!/bin/sh
# Build and launch the Code Police indexed demo on an accelerated Amiga, in
# FS-UAE. The study's target is a 68060 (documentation/amiga-aga-feasibility.md
# §3); see the CPU note below for why the default here is a 68040.
#
# Usage:
#   ./amiga/run-fs-uae-accelerator.sh                 # build, stage and play
#   BUILD=0 ./amiga/run-fs-uae-accelerator.sh        # reuse the existing binaries
#   CPU=68060 ./amiga/run-fs-uae-accelerator.sh      # try the 68060 (see note)
#   START_TICK=20000 ./amiga/run-fs-uae-accelerator.sh   # start at another tick
#
# CPU note. Our binary contains no floating-point and no 68060-only cache
# instruction (verified by disassembly), so it runs on any 68020 or later. The
# fastest emulated CPU that boots here is the 68040: with FS-UAE 3.2.35 and the
# A1200/A4000 Kickstart 3.0/3.1 ROMs, a 68060 makes the ROM's FPU probe trap inside
# ROM ("FPU EXCEPTION ... PC=00F80C9x") and the machine never reaches the desktop. A
# real 68060 needs the accelerator card's own boot ROM, which FS-UAE does not bundle
# (only AROS), so CPU=68060 is offered for completeness and is expected to hang.
# This does not affect the port: the same integer code runs on a real 68060.
#
# Caveat, stated in the study (§11.2): the emulator gives the instruction set, not
# a real processor pipeline or AGA bus contention, so frame rate here is indicative
# only. A real machine is required before any performance claim.
set -eu

project=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
root=$(CDPATH= cd -- "$project/.." && pwd)
fsuae=${FSUAE_BIN:-fs-uae}
hd="$project/build/hd"
pack="$project/build/native-assets/assets.cpix"
frames="$root/native-sdl2/build/amiga-aga-frames"
rom=${KICKSTART:-"$HOME/Documents/Amiga/amiga-roms/Kickstart 3.1 (40.069) (A1200) (Commodore) (1993).rom"}
cpu=${CPU:-68040}
start=${START_TICK:-760}
# The generated config lives next to the base one, per CPU.
config="$project/build/code-police-aga-$cpu.fs-uae"

if ! command -v "$fsuae" >/dev/null 2>&1; then
    echo "error: cannot find FS-UAE ('$fsuae')" >&2
    exit 1
fi
if [ ! -d "$hd" ]; then
    echo "error: hard-dir not found: $hd (run ./amiga/run-fs-uae.sh once)" >&2
    exit 1
fi
if [ ! -f "$rom" ]; then
    echo "error: Kickstart ROM not found: $rom" >&2
    exit 1
fi

if [ "${BUILD:-1}" = "1" ]; then
    # The indexed pack is derived offline from the verified engine's frame dumps.
    # Build it only when missing; it is 560 KiB and slow to regenerate.
    if [ ! -f "$pack" ]; then
        if [ ! -d "$frames" ]; then
            echo "error: no frame dumps in $frames;" >&2
            echo "       run ./native-sdl2/tools/amiga-aga-palette.sh first" >&2
            exit 1
        fi
        echo "> building the indexed pack from $frames"
        python3 "$project/tools/build_assets.py" "$frames" "$root/native-sdl2/assets" \
            "$project/build/native-assets"
    fi
    # EMBED=1 links the pack into the AGA binary; CPU targets the accelerator.
    RUN=0 CPU="$cpu" EMBED=1 "$project/build.sh"
    cp "$project/build/$cpu/code-police-aga" "$hd/code-police-aga"
    cp "$pack" "$hd/assets/assets.cpix"
    cp "$root/native-sdl2/assets/scene.txt" "$hd/assets/scene.txt"
fi

# A complete config, generated rather than edited, so the accelerated model and CPU
# are explicit. The A4000 model is used because it is the accelerator-class machine
# and boots with the 68040; the 68020 build in run-fs-uae.sh stays the stock A1200
# reference.
cat > "$config" <<EOF
# Generated by amiga/run-fs-uae-accelerator.sh, CPU=$cpu. Not checked in.
[fs-uae]
amiga_model = A4000
uae_cpu_model = $cpu
uae_fpu_model = $cpu
uae_cpu_speed = max
chip_memory = 2048
fast_memory = 8192
kickstart_file = $rom
hard_drive_0 = $hd
hard_drive_0_label = CP
hard_drive_0_read_only = 0
hard_drive_0_priority = 10
fullscreen = 0
window_width = 640
window_height = 512
automatic_input_grab = 0
joystick_port_1 = none
EOF

# Boot straight into the indexed demo, started at part 1 by default.
printf 'Assign LIBS: CP:Libs\nCP:code-police-aga CP:assets play CP:assets/assets.cpix %s\nEcho "exit=$RC" >CP:out.txt\n' \
    "$start" > "$hd/s/startup-sequence"

echo "> FS-UAE, CPU=$cpu (accelerator class), $config"
echo "> play CP:assets/assets.cpix $start"
exec "$fsuae" "$config"
