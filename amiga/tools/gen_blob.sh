#!/bin/sh
# Assemble the CPIX pack into read-only data (milestone N1b).
#
# The native runtime must open no files and decode nothing at start-up. This
# turns amiga/build/native-assets/assets.cpix into an m68k assembly file that
# .incbin's the bytes, so the pack is part of the executable and the loader finds
# it in rodata. Pass AGART_EMBEDDED and link the produced object (build.sh does
# this when EMBED=1).
#
# Symbol naming: the AmigaPorts C ABI prefixes C identifiers with an underscore,
# so the labels are _agart_pack / _agart_pack_end and the C names in
# agart_embed.c are agart_pack / agart_pack_end.
set -eu
project=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
pack="${1:-$project/build/native-assets/assets.cpix}"
out="${2:-$project/build/native-assets/assets_pack.s}"

if [ ! -f "$pack" ]; then
    echo "error: no CPIX pack at $pack; run amiga/tools/build_assets.py first" >&2
    exit 1
fi

abs=$(CDPATH= cd -- "$(dirname -- "$pack")" && pwd)/$(basename -- "$pack")
size=$(wc -c < "$pack" | tr -d ' ')

cat > "$out" <<EOF
/* Generated by amiga/build/gen_blob.sh from $(basename -- "$pack") ($size bytes).
 * The CPIX pack is embedded read-only so the target performs no asset I/O. */
    .section .rodata
    .even
    .globl _agart_pack
_agart_pack:
    .incbin "$abs"
    .globl _agart_pack_end
_agart_pack_end:
    .even
EOF

echo "embedded $size bytes from $pack -> $out"
